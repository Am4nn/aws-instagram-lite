export interface CheckResult {
  service: string;
  feature: string;
  ok: boolean;
  notes: string;
  ms: number;
}

const cell = (s: string) => s.replace(/\|/g, "\|").replace(/\n/g, " ");

export function renderReport(results: CheckResult[], meta: { flociVersion: string; date: string; setupNotes?: string[] }): string {
  const rows = results.map(
    (r) => `| ${r.service} | ${cell(r.feature)} | ${r.ok ? "✅" : "❌"} | ${cell(r.notes)} | ${r.ms} |`,
  );
  const failed = results.filter((r) => !r.ok);
  const passed = results.length - failed.length;
  return [
    "# Floci compatibility report",
    "",
    `Floci ${meta.flociVersion} · ${meta.date} · ${passed}/${results.length} checks passed`,
    "",
    "Generated by `npm run spike`: deploys a throwaway CDK stack with every service",
    "Instagram-lite needs, exercises each one through the AWS SDK, then destroys it.",
    "",
    "| Service | Feature | Works? | Notes | ms |",
    "|---|---|---|---|---|",
    ...rows,
    "",
    "## Workarounds needed",
    "",
    ...(failed.length ? failed.map((r) => `- **${r.service}**: ${r.feature}: ${r.notes}`) : ["None."]),
    "",
    "## Setup notes",
    "",
    ...(meta.setupNotes ?? []).map((n) => `- ${n}`),
    "",
  ].join("\n");
}
